"""Positional engine tests.

Every fixture is synthetic, generated by scripts/make_synthetic_fixtures.py.
Real court records never enter this repository, including in tests.

The file-based tests exercise the real acquisition paths (text-layer PDF,
OCR on a scanned PDF, OCR on a TIFF) and skip cleanly when poppler or
tesseract is not installed, so the pure-Python tests still run anywhere.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from extract_text import extract, extract_deterministic
from extract_text.deterministic.summons import parse_address, repair_house_numbers
from extract_text.documents import have
from extract_text.layout import Word, cluster_lines, strip_line_number_rail

FIXTURES = Path(__file__).parent / "fixtures"

needs_poppler = pytest.mark.skipif(
    not (have("pdftotext") and have("pdfinfo") and have("pdftoppm")),
    reason="poppler not installed",
)
needs_tesseract = pytest.mark.skipif(
    not have("tesseract"), reason="tesseract not installed"
)


