def test_rail_digits_are_stripped_and_body_text_kept():
    words = [
        Word(1, 0.05, 0.10, 0.07, 0.11, "17"),          # rail digit, left band
        Word(1, 0.05, 0.14, 0.07, 0.15, "l4"),          # OCR-mangled rail digit
        Word(1, 0.95, 0.10, 0.97, 0.11, "18"),          # right-margin rail digit
        Word(1, 0.20, 0.10, 0.25, 0.11, "TO:"),         # body text at same height
        Word(1, 0.05, 0.50, 0.09, 0.51, "1234"),        # 4-digit number: NOT rail
    ]
    kept = [w.text for w in strip_line_number_rail(words)]
    assert kept == ["TO:", "1234"]


def test_cluster_lines_groups_by_vertical_overlap():
    words = [
        Word(1, 0.4, 0.30, 0.5, 0.31, "MAIN"),
        Word(1, 0.2, 0.30, 0.3, 0.31, "100"),
        Word(1, 0.2, 0.35, 0.3, 0.36, "SEATTLE,"),
    ]
    lines = cluster_lines(words)
    assert [l.text for l in lines] == ["100 MAIN", "SEATTLE,"]


