"""Positional engine tests.

Every fixture is synthetic, generated by scripts/make_synthetic_fixtures.py.
Real court records never enter this repository, including in tests.

The file-based tests exercise the real acquisition paths (text-layer PDF,
OCR on a scanned PDF, OCR on a TIFF) and skip cleanly when poppler or
tesseract is not installed, so the pure-Python tests still run anywhere.
"""

