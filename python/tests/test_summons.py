def test_parse_address_splits_components():
    p = parse_address("1234 EXAMPLE AVE S APT 5 SEATTLE, WA 98100")
    assert p["street"] == "1234 EXAMPLE AVE S APT 5"
    assert p["unit"] == "APT 5"
    assert p["city"] == "Seattle"
    assert p["state"] == "WA"
    assert p["zip"] == "98100"


def test_parse_address_direction_does_not_eat_the_next_word():
    """'AVE SEATTLE' must not become street 'AVE S' + city 'Eattle'."""
    p = parse_address("9876 SAMPLE AVE SEATTLE, WA 98111")
    assert p["street"] == "9876 SAMPLE AVE"
    assert p["city"] == "Seattle"


def test_parse_address_keeps_suite_as_unit():
    p = parse_address("100 MAIN ST STE 200 SEATTLE, WA 98101")
    assert p["street"] == "100 MAIN ST STE 200"
    assert p["unit"] == "STE 200"


def test_parse_address_returns_none_without_a_street():
    assert parse_address("JANE Q. TENANT and ALL OTHER OCCUPANTS") is None


def test_house_number_ocr_repair():
    repaired, n = repair_house_numbers("L234 EXAMPLE ST")
    assert repaired == "1234 EXAMPLE ST"
    assert n == 1
    # letter-led unit designators and true alphanumerics are never rewritten
    assert repair_house_numbers("123B MAIN ST")[1] == 0


def test_repaired_house_number_flows_through_parse():
    p = parse_address("L234 EXAMPLE ST E PUYALLUP, WA 98374")
    assert p["street"].startswith("1234")
    assert p["house_repaired"] is True


