"""Regenerate src/extract_text/usps_tables.py from USPS Publication 28.

Reads Appendix C1 (street suffix abbreviations) and C2 (secondary unit
designators) from the Postal Service's Postal Explorer pages and writes
them as two plain dictionaries, so the standardizer's tables come from the
source, not from memory, and can be refreshed when the Postal Service
changes them.

    python scripts/fetch_usps_tables.py

C1 lists, for each suffix, its primary name, the spellings in common use,
and the one standard abbreviation. Every spelling maps to the standard.
Where a spelling is listed under two suffixes (MDW appears under both
MEADOW and MEADOWS), the suffix whose standard it is wins.
"""

from __future__ import annotations

import datetime
import html
import re
import sys
import urllib.request
from pathlib import Path

BASE = "https://pe.usps.com/text/pub28/"
C1 = BASE + "28apc_002.htm"
C2 = BASE + "28apc_003.htm"
OUT = Path(__file__).resolve().parents[1] / "src" / "extract_text" / "usps_tables.py"


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "extract-text table refresh"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8", errors="replace")


def table_rows(page: str) -> list[list[str]]:
    rows = []
    for tr in re.findall(r"<tr[^>]*>(.*?)</tr>", page, re.S | re.I):
        cells = re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", tr, re.S | re.I)
        rows.append([" ".join(html.unescape(re.sub(r"<[^>]+>", " ", c)).split()) for c in cells])
    return rows


def suffixes(page: str) -> dict[str, str]:
    groups, std = [], None
    for r in table_rows(page)[2:]:
        if len(r) == 3 and r[2]:
            std = r[2].upper()
            groups.append((std, {r[0].upper(), r[1].upper(), std}))
        elif len(r) == 1 and r[0] and std:
            groups[-1][1].add(r[0].upper())
    out = {std: std for std, _ in groups}
    for std, names in groups:
        for name in names:
            out.setdefault(name, std)
    return dict(sorted(out.items()))


def units(page: str) -> dict[str, str]:
    out = {}
    for r in table_rows(page)[2:]:
        if len(r) == 2 and r[1]:
            std = r[1].rstrip("*").upper()
            out[r[0].upper()] = std
            out[std] = std
    return dict(sorted(out.items()))


def main() -> int:
    s, u = suffixes(fetch(C1)), units(fetch(C2))
    if len(set(s.values())) < 150 or "APARTMENT" not in u:
        print("the USPS pages did not parse as expected; nothing written", file=sys.stderr)
        return 1
    today = datetime.date.today().isoformat()
    OUT.write_text(
        '"""USPS Publication 28 tables, generated by scripts/fetch_usps_tables.py.\n\n'
        f"Source: {C1} (C1, street suffixes)\nand {C2} (C2, secondary unit designators),\n"
        f'retrieved {today}. Do not edit by hand; rerun the script."""\n\n'
        f"SUFFIXES = {s!r}\n\nUNITS = {u!r}\n"
    )
    print(f"wrote {OUT.name}: {len(s)} suffix spellings, {len(set(s.values()))} standards, "
          f"{len(u)} unit designators", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
