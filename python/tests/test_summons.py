def _assert_summons_extraction(x):
    r = x.record
    assert r.case_number == "25-2-00001-0"
    assert [p.name for p in r.plaintiffs] == ["EXAMPLE PROPERTY LLC"]
    assert r.plaintiffs[0].is_business is True
    assert [d.name for d in r.defendants] == ["JANE Q. TENANT", "JON Q. TENANT"]
    assert r.defendant_address.street == "1234 EXAMPLE AVE S APT 5"
    assert r.defendant_address.city == "Seattle"
    assert r.defendant_address.zip == "98100"
    assert r.attorney.firm == "EXAMPLE LAW GROUP PLLC"
    assert r.attorney.address.street == "100 MAIN ST STE 200"
    assert r.attorney.address.zip == "98101"
    assert r.attorney.phone == "206-555-0100"
    assert r.attorney.bar_numbers == "99999"
    # the defendant and attorney addresses must never be the same thing
    assert r.defendant_address.street != r.attorney.address.street
    assert "defendant_equals_attorney" not in x.flags
    assert x.flags == []
    # audit trail: the value knows the rule that produced it
    assert x.evidence["defendant_address"].anchor == "to_block"
    assert x.evidence["attorney"].anchor == "attorney_block"


