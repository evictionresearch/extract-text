"""Backend interface and the grounding check both AI backends share.

A language model will happily return a well-formed record for a document that
says none of it. The defense here is to require a verbatim quote for every
populated field and then verify that quote against the source ourselves. The
model is never asked to score its own confidence, because that number would be
generated by the same process that generated the error.
"""

from __future__ import annotations

import re
from typing import Protocol, runtime_checkable

from ..schema import AIExtraction, Evidence, Extraction

SYSTEM_PROMPT = """\
You extract structured data from United States court records, most often \
eviction and unlawful detainer filings, dockets, and judgments.

Rules:

1. Extract only what the document states. If a field is not in the document, \
leave it null. A missing field is a correct answer; a guessed one is not.
2. Do not normalize, expand, or correct what the document says. Record the case \
type as written. Keep the party name as printed, including middle initials, \
suffixes, and "DOES 1-10" style placeholders.
3. For every field you populate, supply the verbatim text from the document \
that supports it in the evidence map, keyed by dotted field path \
(for example "case_number", "judgment.amount", "defendants.0.name"). Quote \
exactly. Do not paraphrase, reorder, or clean up whitespace inside the quote.
4. If you cannot supply a verbatim quote for a value, do not report the value.
5. Plaintiffs are the filing party, typically the landlord or property owner. \
Defendants are the responding party, typically the tenant. Do not infer which \
is which from the names.
6. Money amounts are numbers in dollars, without currency symbols or commas.
"""


@runtime_checkable
class ExtractionBackend(Protocol):
    """Anything that can turn document text into an `Extraction`."""

    name: str

    def extract(self, text: str) -> Extraction: ...


def _normalize(s: str) -> str:
    """Collapse whitespace so a quote survives PDF line wrapping."""
    return re.sub(r"\s+", " ", s).strip()


def ground(ai: AIExtraction, source: str, backend: str) -> Extraction:
    """Locate each quoted span in the source and assemble an `Extraction`.

    A quote is grounded when it occurs in the source, either verbatim or after
    whitespace normalization. Anything else is reported with `grounded=False`
    and should be treated as unverified, not as an extraction failure. Callers
    decide what to do with it; `Extraction.ungrounded_fields()` lists them.
    """
    normalized_source = _normalize(source)
    evidence: dict[str, Evidence] = {}

    for path, quote in ai.evidence.items():
        index = source.find(quote)
        if index >= 0:
            evidence[path] = Evidence(
                quote=quote, span=(index, index + len(quote)), grounded=True
            )
            continue

        # Fall back to a whitespace-insensitive search. PDF extraction breaks
        # lines mid-phrase, so an otherwise honest quote often fails an exact
        # match. Offsets into the normalized text are not offsets into the
        # source, so span stays None here.
        found = _normalize(quote) in normalized_source
        evidence[path] = Evidence(quote=quote, span=None, grounded=found)

    return Extraction(
        record=ai.record, method="ai", backend=backend, evidence=evidence
    )
